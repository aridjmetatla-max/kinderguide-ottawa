"""Nearest bus stop and O-Train station for each provider -> app/data/transit.js
Source: OpenStreetMap (ODbL), tools/sources/osm_transit.json, made with one Overpass query:
  node["highway"="bus_stop"] + nwr["railway"="station"] + nwr["public_transport"="station"] in the Ottawa area.
Only O-Train stations that are open count: stations tagged as under construction or proposed,
or with an opening date after 2024 (not confirmed open), are left out."""
import json, math, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / 'app' if (ROOT / 'app').is_dir() else ROOT   # this project folder, or the published repo (tools/ next to the site)
SRC = json.loads((ROOT / 'tools/sources/osm_transit.json').read_text())
PROVIDERS = json.loads(re.search(r'const PROVIDERS = (\[.*\]);', (SITE / 'data/providers.js').read_text()).group(1))
BUS_M, TRAIN_M = 400, 1000   # about a 5-minute walk to a bus stop, about 12 minutes to a station

def metres(a, b):
    r = math.radians
    h = math.sin(r(b[0] - a[0]) / 2) ** 2 + math.cos(r(a[0])) * math.cos(r(b[0])) * math.sin(r(b[1] - a[1]) / 2) ** 2
    return 2 * 6371000 * math.asin(math.sqrt(h))

def is_open_otrain(tg):
    if tg.get('station') != 'light_rail' and tg.get('network') not in ('O-Train', 'Confederation Line'):
        return False
    if tg.get('construction:railway') or tg.get('proposed:railway'):
        return False
    opened = tg.get('opening_date') or tg.get('start_date') or ''
    return opened[:4] <= '2024'

stops, trains = [], {}
for e in SRC['elements']:
    tg = e['tags']
    if tg.get('highway') == 'bus_stop' and 'STO' not in (tg.get('operator', '') + tg.get('network', '')):
        stops.append((e['lat'], e['lon']))
    elif is_open_otrain(tg) and tg.get('name'):
        trains.setdefault(tg['name'], (e['lat'], e['lon']))   # one point per station name

out = {}
for p in PROVIDERS:
    here = (p['lat'], p['lon'])
    near = sorted(metres(here, s) for s in stops)
    st = min(((metres(here, xy), n) for n, xy in trains.items()), default=(1e9, None))
    out[p['id']] = {'bus': round(near[0]) if near else None, 'stops': sum(d <= BUS_M for d in near),
                    'train': st[1] if st[0] <= TRAIN_M else None, 'trainM': round(st[0]) if st[0] <= TRAIN_M else None}

meta = {'source': 'OpenStreetMap contributors (ODbL)', 'downloaded': SRC['downloaded'], 'busMetres': BUS_M, 'trainMetres': TRAIN_M,
        'stations': len(trains), 'stops': len(stops)}
js = '/* Generated by tools/build_transit.py, do not edit by hand */\n'
js += 'const TRANSIT_META = ' + json.dumps(meta) + ';\n'
js += 'const TRANSIT = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
(SITE / 'data/transit.js').write_text(js)
near_bus = sum(v['bus'] is not None and v['bus'] <= BUS_M for v in out.values())
near_train = sum(v['train'] is not None for v in out.values())
print(f"{len(stops)} bus stops, {len(trains)} open O-Train stations: {sorted(trains)}")
print(f"{len(out)} providers: {near_bus} with a bus stop within {BUS_M} m, {near_train} within {TRAIN_M} m of an O-Train station")
