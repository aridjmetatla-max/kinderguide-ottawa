"""Merge providers_raw.json + geocode_cache.json into app/data/providers.js (loaded by the site).
A .js file (not .json) so the site also works when index.html is opened straight from a folder."""
import json, math, os, re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / 'app' if (ROOT / 'app').is_dir() else ROOT   # this project folder, or the published repo (tools/ next to the site)
raw = json.loads((SITE / 'data/providers_raw.json').read_text())
geo = json.loads((SITE / 'data/geocode_cache.json').read_text())
# Dates: when the file was downloaded, and the City's own 'last updated' date on the open data portal
OLD = (SITE / 'data/providers.js').read_text() if (SITE / 'data/providers.js').exists() else ''
def old_meta(k, default):
    m = re.search(r'"' + k + r'": "([^"]*)"', OLD)
    return m.group(1) if m else default
DOWNLOADED = os.environ.get('KG_DOWNLOADED') or old_meta('downloaded', '2026-10-15')
CITY_UPDATED = os.environ.get('KG_CITY_UPDATED') or old_meta('cityUpdated', '2026-08-10')
# Manual fix: OpenStreetMap does not know this street number; use the street itself
MANUAL = {'c58': {'lat': 45.3983658, 'lon': -75.6323906, 'how': 'street'}}
# Privacy: these licensees are individual people, not organisations, so their names are not shown
PERSON_LICENSEES = {'c33', 'c123', 'c124', 'c125', 'c126', 'c127', 'c168', 'c304'}
# Programs checked by hand on 2026-11-01 (c1 to c315, h316 to h329). For any program added later, the licensee's
# name is shown only if it is clearly an organisation; otherwise it is hidden and listed for the team to check.
REVIEWED_UP_TO = 329
ORG = re.compile(r"\b(inc|incorporated|ltd|limited|lt[ée]e|corp|corporation|co-?op|cooperative|association|society|foundation|"
                 r"centre|center|services|church|school|board|club|ymca|ywca|university|college|city|community|children|child|"
                 r"daycare|garderie|montessori|academy|group|organi[sz]ation|enr)\b|\d", re.I)

out, spots, missing = [], defaultdict(list), []
for p in raw:
    g = MANUAL.get(p['id']) or geo.get(p['id'])
    if not g:   # not found on the map: left out (and listed below) rather than placed in the wrong spot
        missing.append(p['name']); continue
    q = dict(p)
    if p['id'] in PERSON_LICENSEES: q['operator'] = None
    elif int(p['id'][1:]) > REVIEWED_UP_TO and q.get('operator') and not ORG.search(q['operator']):
        q['operator'] = None; print('Licensee name hidden (may be a person), please check:', p['id'], p['name'])
    q['lat'], q['lon'] = round(g['lat'], 6), round(g['lon'], 6)
    q['approx'] = g['how'] in ('postal', 'street')   # location is approximate (postal code or street only)
    spots[(q['lat'], q['lon'])].append(q)
    out.append(q)
# Programs in the same building: fan them out ~15 m so each marker can be tapped
for group in spots.values():
    for i, q in enumerate(group[1:], 1):
        a = i * 2 * math.pi / len(group)
        q['lat'] = round(q['lat'] + 0.00014 * math.sin(a), 6)
        q['lon'] = round(q['lon'] + 0.0002 * math.cos(a), 6)

meta = {'source': 'City of Ottawa Open Data, Licensed Child Care Providers (Children\'s_Services_Agencies_List.xlsx)',
        'downloaded': DOWNLOADED, 'cityUpdated': CITY_UPDATED,
        'geocoding': 'OpenStreetMap Nominatim, October 2026; approximate where marked'}
js = '/* Generated by tools/build_data.py, do not edit by hand */\n'
js += 'const DATA_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n'
js += 'const PROVIDERS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
(SITE / 'data/providers.js').write_text(js)
print(len(out), 'providers,', sum(q['approx'] for q in out), 'approximate locations ->', SITE / 'data/providers.js')
if missing: print('Left out (no map location):', '; '.join(missing))
